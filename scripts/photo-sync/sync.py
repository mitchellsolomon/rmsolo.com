#!/usr/bin/env python3
"""Publish only album exports, from an isolated checkout; never modify Photos."""
import argparse
import fcntl
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile

GENERATED = Path('src/app/photography/photos.generated.ts')
ASSETS = Path('src/assets/photography/synced')

def run(args, cwd=None, timeout=900):
    return subprocess.run([str(a) for a in args], cwd=cwd, check=True,
                          text=True, capture_output=True, timeout=timeout,
                          env={**os.environ, 'GIT_TERMINAL_PROMPT': '0'}).stdout.strip()

def prepare(cache, repo):
    photos = json.loads((cache / 'manifest.json').read_text())
    if not isinstance(photos, list) or not 1 <= len(photos) <= 200:
        raise ValueError('Expected 1–200 photographs; refusing an empty publication')
    identifiers = set()
    sources = set()
    for photo in photos:
        if not re.fullmatch(r'[a-f0-9]{64}', photo['id']) or photo['id'] in identifiers:
            raise ValueError('Invalid or duplicate photo identity')
        identifiers.add(photo['id'])
        if not re.fullmatch(r'[a-f0-9]{64}\.jpg', photo['file']):
            raise ValueError('Invalid image filename')
        file = cache / photo['file']
        if file.is_symlink() or hashlib.sha256(file.read_bytes()).hexdigest() + '.jpg' != photo['file']:
            raise ValueError('Image checksum mismatch')
        if not all(isinstance(photo[k], int) and 0 < photo[k] <= 2400 for k in ('width', 'height')):
            raise ValueError('Invalid image dimensions')
        sources.add(photo['file'])
    lines = ['// Generated by the Mac album sync. Do not edit.', 'import type { Photograph } from "./photos";']
    imports = {file: f'photo{index}' for index, file in enumerate(sorted(sources))}
    for file, name in imports.items():
        lines.append(f'import {name} from "@/assets/photography/synced/{file}";')
    lines.append('\nexport const syncedPhotographs: Photograph[] = [')
    for photo in photos:
        lines.append('  { id: ' + json.dumps(photo['id']) + ', src: ' + imports[photo['file']] +
                     ', alt: "Photograph by Mitchell Solomon" },')
    lines.append('];\n')
    destination = repo / ASSETS
    destination.mkdir(parents=True, exist_ok=True)
    for file in sources:
        shutil.copyfile(cache / file, destination / file)
    # Only this generated directory is managed. No hand-maintained photos are removed.
    for file in destination.glob('*.jpg'):
        if file.name not in sources:
            file.unlink()
    (repo / GENERATED).write_text('\n'.join(lines))
    return len(photos)

def sync(config):
    repo, cache = Path(config['checkout']), Path(config['cache'])
    cache.mkdir(parents=True, exist_ok=True)
    with (cache / 'sync.lock').open('w') as lock:
        try:
            fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            print('A sync is already running.')
            return
        if run(['git', 'remote', 'get-url', 'origin'], repo) != config['remote']:
            raise ValueError('Unexpected repository remote')
        if run(['git', 'branch', '--show-current'], repo) != 'main':
            raise ValueError('Sync checkout must be on main')
        if run(['git', 'status', '--porcelain'], repo):
            raise ValueError('Sync checkout has unfinished changes; inspect it before retrying')
        run(['git', 'pull', '--ff-only', 'origin', 'main'], repo)
        run([config['helper'], '--export', config['album'], cache])
        count = prepare(cache, repo)
        run(['git', 'add', '--', ASSETS, GENERATED], repo)
        changed = run(['git', 'diff', '--cached', '--name-only'], repo)
        if changed:
            for name in changed.splitlines():
                if name != str(GENERATED) and not name.startswith(str(ASSETS) + '/'):
                    raise ValueError('Unexpected staged file; refusing to publish')
            run(['git', 'diff', '--cached', '--check'], repo)
            run(['git', 'commit', '-m', f'Sync {count} photographs from publishing album'], repo)
        # Also retries an already-committed update whose earlier push failed offline.
        run(['git', 'push', 'origin', 'main'], repo)
        print(f'Synced {count} photographs. No commit is created when nothing changes.')

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--config', type=Path, required=True)
    args = parser.parse_args()
    try:
        sync(json.loads(args.config.read_text()))
    except (ValueError, KeyError, OSError, subprocess.SubprocessError) as error:
        print(f'Photo sync failed: {error}', file=sys.stderr)
        if isinstance(error, subprocess.CalledProcessError):
            print(error.stderr, file=sys.stderr)
        sys.exit(1)
